// Bundles src/*.luau into dist/ZaridiumUI.lua (single file, string-keyed require shim).
// Usage: node tools/bundle.mjs [--version 1.0.0]
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname, basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");
const outArg = process.argv.indexOf("--out");
const outFile = outArg > -1 ? resolve(process.cwd(), process.argv[outArg + 1]) : join(root, "dist", "ZaridiumUI.lua");
const versionArg = process.argv.indexOf("--version");
const version = versionArg > -1 ? process.argv[versionArg + 1] : "dev";

const ORDER = ["Util", "Color", "IconData", "Core", "Assets", "Icons", "Components", "Controls", "Window", "Library"];
const files = readdirSync(srcDir).filter((f) => f.endsWith(".luau")).map((f) => basename(f, ".luau"));
for (const name of files) if (!ORDER.includes(name)) throw new Error(`Module ${name} is missing from ORDER in tools/bundle.mjs`);
for (const name of ORDER) if (!files.includes(name)) throw new Error(`Module ${name} listed in ORDER but not found in src/`);

const header = `--[[
	Zaridium UI ${version}: Material 3 UI library for Roblox executors.
	https://github.com/MidasRX/Zaridium  |  License: CC BY-NC 4.0 (see LICENSE)
	Icons: Material Symbols (Apache-2.0). Fonts: Google Sans Flex (SIL OFL 1.1).
	Generated by tools/bundle.mjs. Do not edit; edit src/ instead.
--]]
`;

let out = header + `
local __modules, __cache = {}, {}
local function require(name)
	local cached = __cache[name]
	if cached ~= nil then
		return cached
	end
	local factory = __modules[name]
	if not factory then
		error("ZaridiumUI: unknown module '" .. tostring(name) .. "'", 2)
	end
	local value = factory()
	__cache[name] = value
	return value
end
`;

for (const name of ORDER) {
  let source = readFileSync(join(srcDir, `${name}.luau`), "utf8").replace(/\r\n/g, "\n");
  source = source.replace(/^--!\w+\n/, "");
  out += `\n__modules["${name}"] = function()\n${source}\nend\n`;
}
out += `\nreturn require("Library")\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`Wrote ${outFile} (${(out.length / 1024).toFixed(1)} KiB, ${ORDER.length} modules, version ${version})`);